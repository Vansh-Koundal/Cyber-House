# pdf_generator.py
from aiml_engine import explain_risk
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors
import io


def generate_pdf_report(evaluation_data):
    buffer = io.BytesIO()

    # 1. Setup Document with strict margins
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )
    story = []

    # 2. Base Styles Setup
    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=18,
        leading=22,
        textColor=colors.HexColor('#1E293B')
    )

    subtitle_style = ParagraphStyle(
        'DocSubTitle',
        parent=styles['Normal'],
        fontSize=10,
        leading=12,
        textColor=colors.HexColor('#64748B')
    )

    section_heading = ParagraphStyle(
        'SectionHead',
        parent=styles['Heading2'],
        fontSize=12,
        leading=16,
        textColor=colors.HexColor('#0F172A'),
        spaceBefore=10,
        spaceAfter=5
    )

    body_style = ParagraphStyle(
        'DocBody',
        parent=styles['Normal'],
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#334155')
    )

    # 3. Header Section
    story.append(Paragraph("CyberHouse Health Audit Report", title_style))
    story.append(Paragraph("Generated by CyberHouse", subtitle_style))
    story.append(Spacer(1, 15))

    # 4. Score Summary Table
    score = evaluation_data.get("score", 0)
    status = evaluation_data.get("status", "UNKNOWN")
    devices = evaluation_data.get("devices", [])

    summary_table_data = [
        ["Home Safety Score", "Network Status", "Devices Analyzed"],
        [f"{score} / 100", str(status), str(len(devices))]
    ]

    summary_table = Table(summary_table_data, colWidths=[180, 180, 180])
    summary_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#F1F5F9')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor('#334155')),
        ('FONTNAME', (0, 0), (-1, -1), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 10),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
    ]))
    story.append(summary_table)
    story.append(Spacer(1, 15))

    # 5. Device Audit Breakdown
    story.append(Paragraph("Detailed Family Action Checklist", section_heading))
    story.append(Spacer(1, 5))

    for dev in devices:
        ip = dev.get("ip", "N/A")
        vendor = dev.get("vendor", "Unknown Device")
        risks = dev.get("risks", [])

        story.append(Paragraph(f"<b>Device:</b> {ip} — {vendor}", section_heading))

        if not risks:
            story.append(Paragraph("• No high-risk open ports detected.", body_style))
        else:
            cls = dev.get("classification") or {"label": "", "uncertain": True}
            for r in risks:
                ex = explain_risk(cls, vendor, r.get("port"), r.get("severity", "LOW"))
                risk_html = (
                    f"<b>• {ex['title']}</b> [{r.get('severity', 'LOW')}] — {ex['urgency']}, about {ex['time']}<br/>"
                    f"{ex['story']}<br/>"
                    f"<b>Fix:</b> {ex['fix']}"
                )
                story.append(Paragraph(risk_html, body_style))
                story.append(Spacer(1, 4))

        story.append(Spacer(1, 8))

    # 6. Build PDF & Return Buffer
    doc.build(story)
    buffer.seek(0)
    return buffer